"""Data loading utilities for the churn prediction project.

Provides a single function :func:`load_data` that reads the synthetic CSV
generated by :mod:`generate_data` and performs basic validation.
"""

import os
from pathlib import Path
import pandas as pd

DEFAULT_DATA_PATH = Path(__file__).resolve().parents[2] / "data" / "synthetic_churn.csv"


def load_data(path: str | os.PathLike = DEFAULT_DATA_PATH) -> pd.DataFrame:
    """Load the churn dataset.

    Parameters
    ----------
    path:
        Path to the CSV file. If omitted, the function looks for the file
        ``data/synthetic_churn.csv`` relative to the project root.

    Returns
    -------
    pd.DataFrame
        DataFrame with the raw data.
    """
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"Dataset not found at {path!s}. Have you run generate_data.py?")

    df = pd.read_csv(path)
    # Basic sanity checks – raise early if something is missing
    required = {
        "customer_id",
        "tenure_months",
        "monthly_charges",
        "total_charges",
        "num_logins",
        "support_tickets",
        "contract_type",
        "plan_type",
        "churn",
    }
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {', '.join(sorted(missing))}")
    return df
